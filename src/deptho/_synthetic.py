"""Synthetic BTCUSDT-perp data in the exact Binance archive schemas.

Used for tests, CI and offline demos. Prices follow a fat-tailed random walk
with volatility clustering; funding follows a persistent, mostly-positive
process like real perps; book depth thins out when volatility rises.
"""
from __future__ import annotations

import io
import zipfile
from datetime import date, datetime, timedelta, timezone
from pathlib import Path

import numpy as np
import pandas as pd


SYNTHETIC_MARKER = "SYNTHETIC.txt"
SYNTHETIC_TAG = "SYNTHETIC DATA · DEMO"


def _zip_csv(df: pd.DataFrame, path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    buf = io.StringIO()
    df.to_csv(buf, index=False)
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr(path.with_suffix(".csv").name, buf.getvalue())
    return path


def _ms(d: date) -> int:
    return int(datetime(d.year, d.month, d.day, tzinfo=timezone.utc).timestamp() * 1000)


def make(dest: str | Path, symbol: str = "BTCUSDT", tick_day: date = date(2026, 9, 30),
         kline_days: int = 90, trades_per_day: int = 400_000, seed: int = 23) -> dict[str, list[Path]]:
    rng = np.random.default_rng(seed)
    dest = Path(dest)
    dest.mkdir(parents=True, exist_ok=True)
    # Marker so reports built from this folder are labelled as synthetic.
    (dest / SYNTHETIC_MARKER).write_text("Generated by deptho._synthetic; not market data.\n", encoding="utf-8")
    out: dict[str, list[Path]] = {"klines": [], "fundingRate": [], "aggTrades": [], "bookDepth": []}
    start = tick_day - timedelta(days=kline_days - 1)

    # 1m klines with GARCH-ish vol clustering.
    n = kline_days * 1440
    vol = np.empty(n)
    v = 6e-4
    shocks = rng.standard_t(4, n) / np.sqrt(2)
    for i in range(n):
        v = np.sqrt(3.6e-9 + 0.06 * (v * shocks[i - 1]) ** 2 + 0.93 * v * v) if i else v
        vol[i] = v
    drift = np.repeat(rng.normal(0.0, 3e-6, kline_days * 6), 240)[:n]  # 4h regimes, long bias
    rets = drift + vol * shocks
    close = 62_000 * np.exp(np.cumsum(rets))
    open_ = np.r_[62_000, close[:-1]]
    spread = np.abs(rng.normal(0, 1, n)) * vol * close
    high, low = np.maximum(open_, close) + spread, np.minimum(open_, close) - spread
    volume = rng.gamma(2.0, 40.0, n) * (vol / 6e-4)
    t0 = _ms(start)
    open_time = t0 + np.arange(n) * 60_000
    for d in range(kline_days):
        sl = slice(d * 1440, (d + 1) * 1440)
        day = start + timedelta(days=d)
        df = pd.DataFrame({
            "open_time": open_time[sl], "open": open_[sl].round(1), "high": high[sl].round(1),
            "low": low[sl].round(1), "close": close[sl].round(1), "volume": volume[sl].round(3),
            "close_time": open_time[sl] + 59_999, "quote_volume": (volume[sl] * close[sl]).round(2),
            "count": rng.integers(500, 5000, 1440), "taker_buy_volume": (volume[sl] * 0.5).round(3),
            "taker_buy_quote_volume": (volume[sl] * close[sl] * 0.5).round(2), "ignore": 0,
        })
        out["klines"].append(_zip_csv(df, dest / f"{symbol}-1m-{day.isoformat()}.zip"))

    # Funding every 8h: AR(1) around +1bp, spikes in trending regimes.
    m = kline_days * 3
    f = np.empty(m)
    x = 1e-4
    for i in range(m):
        x = 1e-4 + 0.85 * (x - 1e-4) + rng.normal(0, 6e-5) + 3.0 * drift[i * 480]
        f[i] = np.clip(x, -7.5e-4, 7.5e-4)
    calc = t0 + np.arange(m) * 8 * 3600_000
    fr = pd.DataFrame({"calc_time": calc, "funding_interval_hours": 8, "last_funding_rate": f.round(8)})
    months = pd.to_datetime(fr["calc_time"], unit="ms").dt.strftime("%Y-%m")
    for mon, g in fr.groupby(months):
        out["fundingRate"].append(_zip_csv(g, dest / f"{symbol}-fundingRate-{mon}.zip"))

    # Tick day: Poisson trade arrivals walking off the last day of klines.
    k = trades_per_day
    tday_ms = _ms(tick_day)
    times = np.sort(rng.integers(0, 86_400_000, k)) + tday_ms
    minute = (times - tday_ms) // 60_000
    day_close = close[-1440:]
    day_vol = vol[-1440:]
    base = np.r_[day_close[0], day_close[:-1]][minute]
    frac = ((times - tday_ms) % 60_000) / 60_000
    tgt = np.r_[day_close[0], day_close[:-1]][minute] + (day_close[minute] - base) * frac
    noise = rng.normal(0, 1, k) * day_vol[minute] * tgt * 0.15
    side_buy = rng.random(k) < 0.5
    tick = 0.1
    px = np.round((tgt + noise + np.where(side_buy, 0.5, -0.5) * tick) / tick) * tick
    qty = np.round(rng.lognormal(-4.0, 1.6, k), 3).clip(0.001)
    ids = 3_000_000_000 + np.arange(k)
    agg = pd.DataFrame({
        "agg_trade_id": ids, "price": px.round(1), "quantity": qty, "first_trade_id": ids * 3,
        "last_trade_id": ids * 3 + rng.integers(0, 3, k), "transact_time": times,
        "is_buyer_maker": np.where(side_buy, "false", "true"),
    })
    out["aggTrades"].append(_zip_csv(agg, dest / f"{symbol}-aggTrades-{tick_day.isoformat()}.zip"))

    # bookDepth: snapshots every 30s, cumulative notional within +/-1..5%.
    snaps = np.arange(0, 86_400, 30)
    rows = []
    for s in snaps:
        mi = min(s // 60, 1439)
        liq = 1.0 / (day_vol[mi] / 6e-4)
        p = day_close[mi]
        for pct in (-5, -4, -3, -2, -1, -0.2, 0.2, 1, 2, 3, 4, 5):
            notional = 6e7 * abs(pct) ** 0.8 * liq * rng.uniform(0.85, 1.15)
            rows.append((pd.Timestamp(tday_ms + s * 1000, unit="ms").strftime("%Y-%m-%d %H:%M:%S"),
                         pct, round(notional / p, 3), round(notional, 2)))
    bd = pd.DataFrame(rows, columns=["timestamp", "percentage", "depth", "notional"])
    out["bookDepth"].append(_zip_csv(bd, dest / f"{symbol}-bookDepth-{tick_day.isoformat()}.zip"))
    return out
